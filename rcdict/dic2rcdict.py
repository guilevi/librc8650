#!/usr/bin/env python3
# SPDX-License-Identifier: BSD-3-Clause
"""dic2rcdict --- convert an RC Systems .dic exception dictionary to rcdict.

The source is the text form RCStudio compiles: one exception per line, in the
RC8650 datasheet's L(F)R=P syntax, ISO-8859-1, with Table 5 phoneme mnemonics
on the right-hand side.  The target is an rcdict tab-separated dictionary using
the `rule` matcher, in UTF-8:

    rule <TAB> <TAB> L(F)R <TAB> [P]

The mapping is one-to-one and needs no editing of the rules themselves -- the
pattern column carries the exception verbatim, and the pronunciation only has
to be wrapped in the phoneme-span brackets rcdict already understands.  What
changes is the encoding (ISO-8859-1 to UTF-8) and the split of the file at the
Character-mode marker, which rcdict has no equivalent for.

    python3 rcdict/dic2rcdict.py RCStudio/Samples/Dictionaries/Spanish.dic \
        -o spanish.dict

This lives beside rcdict itself, and is mirrored into doubletalk-pc by
sync-to-doubletalk-pc.sh, because the dictionaries it produces are read by both
engines: a converter kept next to only one of them would be a converter one of
them did not know it had.
"""

import argparse
import re
import sys

RULE_RE = re.compile(r"^(.*?)\((.*?)\)(.*?)=(.*)$")

# Table 5 letter mnemonics, plus the pause symbols and Table 6 modifiers that
# may appear in a pronunciation.  Kept in step with rcdict.c's table5[].
TABLE5 = set("""AA AE AH AW AX AY CH DH DX EH EI ER EW EY IH IX IY KX NG NY
OW OY PX RR SH TH TX UH UW WH YY ZH A B D E F G H I J K L M N O P R S T U V W
Y Z""".split())
PAUSES = ".,'"
MODIFIERS = "/\\+-><"


# Table 22's classes are English, and that is the one part of the rule language
# that does not travel: with the stock vowel list an accented letter is not a
# letter at all, so '$' matches inside a word and the single-letter rules start
# firing -- "mas" comes out spelled aloud.  rcdict lets a dictionary declare its
# own alphabet; these are the declarations each language needs.
CLASSES = {
    "es": [
        ("#", "a e i o u y á é í ó ú ü"),
        ("+", "e i y é í"),
        ("^", "b c d f g h j k l m n ñ p q r s t v w x y z"),
        ("?", "b d g j l m n ñ r v w z"),
    ],
}


def convert(text, name):
    """Yield (mode, kind, payload) for every line of a .dic file.

    mode is 'text' or 'char'; kind is 'rule', 'comment' or 'error'.
    """
    mode = "text"
    for lineno, raw in enumerate(text.replace("\r\n", "\n").replace("\r", "\n").split("\n"), 1):
        s = raw.strip()
        if not s:
            yield mode, "blank", ""
            continue
        if s.startswith(";"):
            yield mode, "comment", s[1:].strip()
            continue
        if s in ("C", "c"):
            mode = "char"
            continue
        m = RULE_RE.match(s)
        if not m:
            yield mode, "error", "%s:%d: not an exception: %r" % (name, lineno, s)
            continue
        left, frag, right, pron = m.groups()
        pattern = "%s(%s)%s" % (left, frag, right)
        if "\t" in pattern:
            yield mode, "error", "%s:%d: tab in pattern" % (name, lineno)
            continue
        yield mode, "rule", (lineno, pattern, pron.split())


def check_phonemes(syms):
    return [s for s in syms if s.upper() not in TABLE5
            and not (len(s) == 1 and (s in PAUSES or s in MODIFIERS))]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source")
    ap.add_argument("-o", "--output", default="-")
    ap.add_argument("-e", "--encoding", default="iso-8859-1",
                    help="source encoding (default iso-8859-1, per RC Systems)")
    ap.add_argument("--lang", default="es")
    ap.add_argument("--char-mode", choices=("drop", "keep"), default="drop",
                    help="what to do with Character-mode exceptions; rcdict has "
                         "no character mode, and the text-mode $(x)$ rules "
                         "already name every letter (default: drop)")
    args = ap.parse_args()

    text = open(args.source, "rb").read().decode(args.encoding)
    out = []
    stats = {"text": 0, "char": 0, "silent": 0, "bad": 0}

    out.append("; Generated by rcdict/dic2rcdict.py from %s" % args.source)
    out.append("; Do not edit here; edit the source dictionary and re-run.")
    out.append(";")
    out.append("#!rcdict 1")
    out.append("#!case insensitive")
    out.append("#!lang %s" % args.lang)
    classes = CLASSES.get(args.lang)
    if classes:
        out.append("")
        out.append("; The alphabet these rules are written against. Without it")
        out.append("; the accented letters are not letters, '$' matches inside")
        out.append("; a word, and the letter-naming rules fire in the middle of")
        out.append("; one. '$' follows '#' and '^'; '*' and ':' follow '^'.")
        for tok, members in classes:
            out.append("#!class %s %s" % (tok, members))
    elif args.lang != "en":
        print("warning: no character classes known for --lang %s; the rules "
              "will be matched against Table 22's English alphabet"
              % args.lang, file=sys.stderr)
    out.append("")

    for mode, kind, payload in convert(text, args.source):
        if mode == "char" and args.char_mode == "drop":
            if kind == "rule":
                stats["char"] += 1
            continue
        if kind == "blank":
            if out and out[-1] != "":
                out.append("")
            continue
        if kind == "comment":
            # RCStudio buries editor anchors (#Hnn) in comments; they carry no
            # meaning outside its dictionary editor.
            if re.fullmatch(r"#H\d+", payload, re.I):
                continue
            out.append("; %s" % payload if payload else ";")
            continue
        if kind == "error":
            print(payload, file=sys.stderr)
            stats["bad"] += 1
            continue

        lineno, pattern, syms = payload
        unknown = check_phonemes(syms)
        if unknown:
            print("%s:%d: not Table 5 symbols: %s"
                  % (args.source, lineno, " ".join(unknown)), file=sys.stderr)
            stats["bad"] += 1
            continue
        stats[mode] += 1
        if not syms:
            stats["silent"] += 1
            out.append("rule\t\t%s\t" % pattern)
        else:
            out.append("rule\t\t%s\t[%s]" % (pattern, " ".join(syms)))

    body = "\n".join(out).rstrip("\n") + "\n"
    if args.output == "-":
        sys.stdout.write(body)
    else:
        open(args.output, "w", encoding="utf-8").write(body)

    print("%d text-mode rules (%d of them silent), %d character-mode rules %s, "
          "%d rejected"
          % (stats["text"], stats["silent"], stats["char"],
             "dropped" if args.char_mode == "drop" else "kept", stats["bad"]),
          file=sys.stderr)


if __name__ == "__main__":
    main()
